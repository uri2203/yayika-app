const LANG_KEY = 'yayika_language';

export async function getSavedLanguage(): Promise<Language> {
  try {
    const saved = await SecureStore.getItemAsync(LANG_KEY);
    if (saved && ['es', 'en', 'pt', 'fr', 'de'].includes(saved)) {
      return saved as Language;
    }
  } catch {}
  return 'es';
}

export async function saveLanguage(lang: Language): Promise<void> {
  try {
    await SecureStore.setItemAsync(LANG_KEY, lang);
  } catch {}
}

export function t(lang: Language, key: string): string {
  return translations[lang]?.[key] || translations['es']?.[key] || key;
}

export function getLanguageName(lang: Language): string {
  const names: Record<Language, string> = {
    es: 'Español',
    en: 'English',
    pt: 'Português',
    fr: 'Français',
    de: 'Deutsch',
  };
  return names[lang];
}

export { translations };
